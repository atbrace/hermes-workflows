#!/usr/bin/env bash
# ue-bead CI-parity gate lane script.
# Mirrors upstream .github/workflows/ci.yml gates on the cluster via crun.
# The gate body is GENERATED at run time from ci.yml (est-rmsro): HERMES_PIN and
# python-version are parsed from the workflow, so parity cannot silently drift
# when ci.yml is repinned. The generated job script is written into the lane dir
# as .ci-job-$$.sh, untracked-but-NOT-ignored: crun stages repo files only
# (--include-untracked uses --exclude-standard, so an ignored name never ships)
# and a host /tmp path never crosses to the node. Removed after the run, as the
# /tmp copy was (the committed fanout copies were the litter est-rmsro swept).
# Verdict cache: $LANE/.ci-verdict (PASS/FAIL + rc + timestamp). CI gate re-invokes
# this script on `every_s` ticks; a PASS cache exits 0 immediately; a FAIL cache is
# honored for 1h (retry sooner only by deleting it).
set -uo pipefail
LANE="$(cd "$(dirname "$0")/.." && pwd)"
V="$LANE/.ci-verdict"
if [ -f "$V" ]; then
  now=$(date +%s); age=$(( now - $(stat -c %Y "$V") ))
  if grep -q '^PASS' "$V"; then exit 0; fi
  if grep -q '^FAIL' "$V" && [ "$age" -lt 3600 ]; then exit 1; fi
fi
export DEBIAN_FRONTEND=noninteractive PIP_BREAK_SYSTEM_PACKAGES=1
JOB="ue-ci-$(basename "$LANE")-$$"
cd "$LANE"
# single source of truth: the workflow file itself (est-rmsro)
PIN="$(sed -n 's/^[[:space:]]*HERMES_PIN:[[:space:]]*\([0-9a-f]\{7,\}\).*/\1/p' .github/workflows/ci.yml | head -1)"
PYV="$(sed -n 's/^[[:space:]]*python-version:[[:space:]]*"\{0,1\}\([0-9.]*\)"\{0,1\}.*/\1/p' .github/workflows/ci.yml | head -1)"
[ -n "$PIN" ] || { echo "FATAL: HERMES_PIN not parseable from .github/workflows/ci.yml"; exit 1; }
JS="$LANE/.ci-job-$$.sh"
# repo-relative or dead: crun ships only files under the repo dir, so a /tmp job
# body reproduces the original defect (container cp dies at its first line).
[ "${JS#"$LANE/"}" != "$JS" ] || { echo "FATAL: generated job script must live inside the lane dir (host /tmp never ships to the node)"; exit 1; }
cat > "$JS" <<EOF
#!/usr/bin/env bash
# GENERATED by ci/ci-parity.sh from .github/workflows/ci.yml — edit the source, not this.
set -u; rc=0
apt-get update -qq >/dev/null 2>&1
apt-get install -y -qq curl ca-certificates tar xz-utils >/dev/null 2>&1
NODE_V=v22.18.0
NODE_A=\$(dpkg --print-architecture); case "\$NODE_A" in amd64) NODE_A=x64;; arm64) NODE_A=arm64;; esac
curl -fsSL "https://nodejs.org/dist/\$NODE_V/node-\$NODE_V-linux-\$NODE_A.tar.xz" -o /tmp/node.tar.xz \\
  && tar -xJf /tmp/node.tar.xz -C /opt \\
  && ln -sf "/opt/node-\$NODE_V-linux-\$NODE_A/bin/node" /usr/local/bin/node \\
  && ln -sf "/opt/node-\$NODE_V-linux-\$NODE_A/bin/npm" /usr/local/bin/npm \\
  || echo "WARN: node \$NODE_V fetch failed — node arms ride apt nodejs 18"
if [ -n "${PYV:-}" ]; then
  apt-get install -y -qq "python${PYV}" "python${PYV}-venv" python3-pip git openssh-client rsync python3-jsonschema nodejs npm >/dev/null 2>&1 \\
    || echo "WARN: python${PYV} unavailable in the image — suite arms ride the image-default interpreter"
fi
apt-get install -y -qq git openssh-client rsync python3-jsonschema nodejs npm python3-pip >/dev/null 2>&1 || echo "WARN: apt partial"
git config --global --add safe.directory '*'
PIN=$PIN
if command -v hermes >/dev/null 2>&1 && hermes --version >/dev/null 2>&1; then
  echo "HERMES: already present"
else
  git clone -q https://github.com/NousResearch/hermes-agent /tmp/hermes-agent \
    && git -C /tmp/hermes-agent checkout -q "\$PIN" \
    && python3 -m pip install -q --break-system-packages uv >/dev/null 2>&1 \
    && uv sync --python 3.14 --directory /tmp/hermes-agent >/dev/null 2>&1 \
    && printf '#!/bin/sh\nexec uv run --project /tmp/hermes-agent hermes "\$@"\n' > /usr/local/bin/hermes \
    && chmod +x /usr/local/bin/hermes \
    || echo "WARN: pinned core bootstrap failed"
fi
echo "=== suite (canonical entry) ==="
if [ -x tools/ci/run.sh ] || [ -f tools/ci/run.sh ]; then
  bash tools/ci/run.sh || rc=1
elif [ -f scripts/suite.py ]; then
  uv run --project /tmp/hermes-agent python3 scripts/suite.py . ci-out || rc=1
else
  echo "FATAL: no canonical suite entry (tools/ci/run.sh or scripts/suite.py)"; rc=1
fi
echo "=== node ESM parse ==="
cp desktop/plugin.js /tmp/ue-plugin.mjs && node --check /tmp/ue-plugin.mjs || rc=1
for f in \$(git ls-files "bin/*.js"); do node --check "\$f" || rc=1; done
[ -f tests/test_edge_routing.mjs ] && { node --experimental-strip-types tests/test_edge_routing.mjs || rc=1; }
echo "=== plugins validate (pinned core) ==="
hermes plugins validate . || { hermes --version 2>/dev/null || echo "NOTE: core absent — validate unrunnable in this image"; rc=1; }
echo "=== doctor ==="
hermes doctor 2>&1 | tail -2 || true
echo "=== scrub audit ==="
if git rev-parse --git-dir >/dev/null 2>&1; then
  python3 scripts/make_public.py /tmp/ue-pub 2>&1 | tail -2 || rc=1
else
  echo "WARN: synced copy carries no git metadata — scrub audit skipped"
fi
echo "CI_PARITY=\$([ \$rc -eq 0 ] && echo GREEN || echo RED)"
exit \$rc
EOF
chmod +x "$JS"
crun run --name "$JOB" --include-untracked --image ubuntu:24.04 -- bash -c "cp .ci-job-$$.sh /ue-ci-job.sh && bash /ue-ci-job.sh"
rc=$?
rm -f "$JS"
if [ "$rc" -eq 0 ]; then echo PASS > "$V"; else echo FAIL > "$V"; fi
echo "rc=$rc $(date -Is)" >> "$V"
exit "$rc"
